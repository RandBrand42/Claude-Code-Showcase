#!/usr/bin/env node
/**
 * build-registry.mjs - discovers every app in the suite and writes ../registry.js for the gallery.
 *
 * An app is any top-level folder that contains BOTH an index.html and an app.json manifest.
 * Adding a new app to the suite = add that folder, run this script (Vercel runs it on every deploy).
 *
 *   node tools/build-registry.mjs
 *
 * app.json fields:
 *   name         (required) display name
 *   kind         (required) category chip, e.g. "Creative"
 *   tagline      (required) one-line pitch
 *   description  (required) 1-2 sentence description
 *   tech         (required) array of short tags
 *   hue          0-360 accent colour for the card           (default 220)
 *   order        sort position, lower first                  (default 1000)
 *   feature      true = visually featured                    (default false)
 *
 * Optional per-app assets: screenshots/hero.png and README.md. Optional gallery thumbnail:
 * assets/thumbs/<folder>.webp (made by tools/make-thumbs.scenario.mjs; falls back to hero.png).
 * Optional site settings in site.config.json: { "title": "...", "repoUrl": "https://github.com/org/repo", "branch": "main" }
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = new Set(['.html', '.css', '.js', '.mjs', '.cjs']);
const SKIP_DIRS = new Set(['screenshots', 'node_modules', '.git', '.vercel']);
const NON_APP = new Set(['docs', 'tools', 'assets', 'node_modules']);

const errors = [], warnings = [];
const read = (p, fallback) => { try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch (e) { if (fallback !== undefined && e.code === 'ENOENT') return fallback; throw e; } };

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(e.name)) continue;
    const p = path.join(dir, e.name);
    e.isDirectory() ? walk(p, out) : out.push(p);
  }
  return out;
}

const site = Object.assign({ title: 'Claude Code Showcase', repoUrl: '', branch: 'main' }, read(path.join(root, 'site.config.json'), {}));
site.repoUrl = String(site.repoUrl || '').replace(/\/+$/, '');

const apps = [];
for (const d of fs.readdirSync(root, { withFileTypes: true })) {
  if (!d.isDirectory() || d.name.startsWith('.') || d.name.startsWith('_') || NON_APP.has(d.name)) continue;
  const dir = path.join(root, d.name);
  const manifestPath = path.join(dir, 'app.json');
  const hasIndex = fs.existsSync(path.join(dir, 'index.html'));
  if (!fs.existsSync(manifestPath)) { if (hasIndex) warnings.push(`${d.name}: has index.html but no app.json - not listed in the gallery`); continue; }
  if (!hasIndex) { errors.push(`${d.name}: app.json present but index.html is missing`); continue; }

  let m;
  try { m = read(manifestPath); } catch (e) { errors.push(`${d.name}/app.json: ${e.message}`); continue; }
  for (const k of ['name', 'kind', 'tagline', 'description']) if (typeof m[k] !== 'string' || !m[k].trim()) errors.push(`${d.name}/app.json: "${k}" must be a non-empty string`);
  if (!Array.isArray(m.tech) || !m.tech.every((t) => typeof t === 'string')) errors.push(`${d.name}/app.json: "tech" must be an array of strings`);
  if (m.hue !== undefined && !(Number.isFinite(m.hue) && m.hue >= 0 && m.hue <= 360)) errors.push(`${d.name}/app.json: "hue" must be a number from 0 to 360`);

  const files = walk(dir).filter((f) => SRC.has(path.extname(f)));
  const lines = files.reduce((n, f) => n + fs.readFileSync(f, 'utf8').split('\n').length, 0);
  const hero = fs.existsSync(path.join(dir, 'screenshots', 'hero.png'));
  const thumb = fs.existsSync(path.join(root, 'assets', 'thumbs', `${d.name}.webp`));
  if (!hero && !thumb) warnings.push(`${d.name}: no screenshots/hero.png or assets/thumbs/${d.name}.webp - the card will show a gradient only`);

  apps.push({
    id: d.name, name: m.name, kind: m.kind, tagline: m.tagline, description: m.description,
    tech: m.tech || [], hue: m.hue ?? 220, order: m.order ?? 1000, feature: !!m.feature,
    image: thumb ? `assets/thumbs/${d.name}.webp` : hero ? `${d.name}/screenshots/hero.png` : '',
    readme: fs.existsSync(path.join(dir, 'README.md')),
    files: files.length, lines,
  });
}

if (errors.length) { console.error('Registry NOT written. Fix these first:\n  - ' + errors.join('\n  - ')); process.exit(1); }

apps.sort((a, b) => a.order - b.order || a.name.localeCompare(b.name));
const stats = [
  ['apps', apps.length],
  ['source files', apps.reduce((n, a) => n + a.files, 0)],
  ['lines of code', apps.reduce((n, a) => n + a.lines, 0)],
  ['runtime dependencies', 0],
];

fs.writeFileSync(path.join(root, 'registry.js'),
  '/* Generated by tools/build-registry.mjs - do not edit by hand. */\n' +
  `window.SHOWCASE_REGISTRY = ${JSON.stringify({ site, stats, apps }, null, 2)};\n`);

console.log(`registry.js written: ${apps.length} apps`);
for (const a of apps) console.log(`  ${String(a.order).padStart(4)}  ${a.id.padEnd(14)} ${String(a.files).padStart(3)} files ${String(a.lines).padStart(6)} lines  image: ${a.image || '(none)'}`);
for (const w of warnings) console.warn('warning: ' + w);
